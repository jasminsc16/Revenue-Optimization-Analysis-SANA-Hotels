d['n']=d.stays_in_weekend_nights+d.stays_in_week_nights
def g(by,df=d):
    t=df.groupby(by,observed=True).agg(bookings=('is_canceled','size'),cancel_rate=('is_canceled','mean'),exp=('expected_revenue','sum'),real=('realized_revenue','sum'),lost=('lost_revenue','sum'))
    t['lost_pct']=t.lost/t.exp; t['share_of_lost']=t.lost/t.lost.sum(); return t.round(3).sort_values('lost',ascending=False)
print(g('hotel'))
print(g('deposit_type'))
print(g(['deposit_type','hotel']))
